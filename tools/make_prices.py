"""Build /prices/ using the shared site shell and the prices content."""
from pathlib import Path
from make_info_page import build_info_page

from v2parts import SITE, Page, VISIBLE, typo

root = Path(SITE)
page = Page(B='../', W='../works/', nav_page='prices', cta_text=tuple(map(typo, (
    'Расскажите о задаче и сроках. Если есть план площадки, сценарий или референсы, пришлите их. Обсудим, с чего начать и что нужно для оценки.',
    'Обсудим бюджет',
    'вашего проекта',
))))
faq = [
    ('Эти суммы относятся к показанным проектам?', 'Работы показаны как примеры подхода. Указанные суммы помогают прикинуть бюджет нового проекта. Точную стоимость считаем после знакомства с задачей и материалами.'),
    ('Можно заказать только концепцию?', 'Да. Можно отдельно придумать концепцию, чтобы согласовать идею, понять, какие материалы и устройства понадобятся, и оценить реализацию.'),
    ('Можно прийти с готовой концепцией или заказать только контент?', 'Да. Можем сделать отдельный ролик, 3D-графику или приложение и передать их вашей команде. Сначала сверим требования к экрану, оборудованию и формату файлов.'),
    ('Входит ли оборудование и застройка?', 'Эти расходы считаем отдельными строками. Можем работать с вашей командой или подключить проверенных застройщиков, если вам удобно вести весь проект через студию.'),
    ('Что меняется, если до открытия осталось мало времени?', 'Сразу скажите дату. Посмотрим, какие материалы готовы, к чему должна быть готова площадка и что реально сделать к сроку. При необходимости предложим сократить объем или разделить задачу на этапы.'),
    ('Можно заложить обновления и поддержку после запуска?', 'Да. Если содержимое будет меняться, обсудим, какие разделы сотрудники смогут обновлять сами. Выезд, удаленную поддержку и новые версии оценим с учетом того, как будет работать экспонат.'),
]
exhibits = {work['id']: work for work in VISIBLE if work['id'] in ('stol', 'shturval')}
tiles = ''.join(page.tile(dict(exhibits[slug], meta=typo(exhibits[slug]['where'])))
                for slug in ('stol', 'shturval'))
body = (root / '_src/prices-content.html').read_text(encoding='utf-8')
body = body.replace('{{exhibit_tiles}}', tiles.rstrip())
body += page.faq([(typo(question), typo(answer)) for question, answer in faq])

title = 'Цены на мультимедиа для музеев и выставок | студия братьев Пе́трович'
description = 'Сколько стоят программа для тачскрина, видеоролик и интерактивный экспонат. Ориентиры по бюджету, примеры работ и что влияет на смету.'
build_info_page(page, 'prices', body, title, description)
