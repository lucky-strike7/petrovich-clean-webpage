"""Build the services page."""
from pathlib import Path

from make_info_page import build_info_page
from v2parts import DATA, SITE, Page, typo

root = Path(SITE)
page = Page(B='../', W='../works/', nav_page='services', cta_text=tuple(map(typo, (
    'Напишите, что хотите показать, где и к какой дате. Если уже есть концепция, сценарий или план площадки, пришлите их. Вместе определим, с чего начать.',
    'Обсудим',
    'ваш проект',
))))
projects = {item['id']: item for item in DATA['projects']}
tiles = ''.join(page.tile(dict(projects[slug], meta=typo(projects[slug]['where'])))
                for slug in ('khersones', 'khakasia'))
body = (root / '_src/services-content.html').read_text(encoding='utf-8')
body = body.replace('{{project_tiles}}', tiles.rstrip())
faq = [
    ('Сколько это стоит?', 'Ориентир такой: программа для тачскрина от 500 тыс. ₽, видеоролик от 700 тыс. ₽, интерактивный экспонат от 900 тыс. ₽. Точную сумму считаем, когда узнаем задачу. Что входит в эти суммы, рассказываем на странице «Цены».'),
    ('Сколько времени занимает работа?', 'Обычно около месяца. Большие проекты, например целый зал, занимают 3–5 месяцев. Если совсем срочно, можем уложиться в две недели.'),
    ('Можно заказать только ролик или одну программу?', 'Да. Необязательно отдавать нам всю мультимедийную часть. Сделаем отдельный ролик, 3D-анимацию или приложение и передадим вашей команде. Сначала сверим требования к экрану, оборудованию и формату файлов.'),
    ('Работаете в регионах?', 'Да, по всей России: от Севастополя до Екатеринбурга. Сами приезжаем на монтаж и запуск своей части.'),
    ('Что будет, если экспонат сломается?', 'Приедем и починим. Многое решаем без выезда: настраиваем удаленный доступ, чтобы проверить экспонат и обновить контент, как в музее «Новый Херсонес».'),
    ('Как с договором и НДС?', 'Работаем по договору, без НДС. Если проект идет через закупку, расскажите как, и вместе подберем удобную схему.'),
]
# Ссылку ставим после typo: она экранирует разметку
body += page.faq([(typo(question), typo(answer).replace('«Цены»', '<a href="../prices/">«Цены»</a>'))
                  for question, answer in faq])
build_info_page(
    page, 'services', body,
    'Мультимедиа для музеев и выставок | Услуги студии братьев Пе́трович',
    'Концепция, интерактивные экспонаты, видео и 3D-графика для музеев, выставочных стендов и мероприятий. Услуги и примеры работ.',
)
